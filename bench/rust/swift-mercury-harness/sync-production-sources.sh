#!/bin/sh
# Copies the production sources the mercury raster path compiles against verbatim into
# this harness and records their SHA-256 in ProductionSources.swift. The harness checks,
# at startup, that both the copy and the repository file still hash to that value, so a
# drifted copy or a changed production file fails loudly instead of benchmarking stale code.
#
# Usage: bench/rust/swift-mercury-harness/sync-production-sources.sh   (then rebuild)
set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../.." && pwd)
TARGET="$HERE/Sources/SwiftMercuryHarness"
DEST="$TARGET/Production"
MANIFEST="$TARGET/ProductionSources.swift"

# The raster path (rasterizer, field, crown, optics, room, response), the inputs it is fed
# (simulation, pose, calibration, noise, metrics), and the overlay model/layout the pose
# ladder and island size are read from.
FILES="
MercuryCalibration.swift
MercuryCrown.swift
MercuryDisplayResponse.swift
MercuryEnvironment.swift
MercuryField.swift
MercuryMetrics.swift
MercuryNoise.swift
MercuryOptics.swift
MercuryPose.swift
MercuryRasterizer.swift
MercurySimulation.swift
RecordingOverlayLayout.swift
RecordingOverlayModel.swift
RecordingOverlaySessionState.swift
"

mkdir -p "$DEST"
rm -f "$DEST"/*.swift
{
    echo "// Generated by sync-production-sources.sh. Do not edit."
    echo ""
    echo "/// Verbatim copies under Production/ and the SHA-256 they had when copied."
    echo "enum ProductionSources {"
    echo "    static let files: [(copy: String, repository: String, sha256: String)] = ["
    for file in $FILES; do
        cp "$ROOT/Sources/Voiceour/$file" "$DEST/$file"
        digest=$(shasum -a 256 "$DEST/$file" | cut -d' ' -f1)
        echo "        (\"Production/$file\", \"Sources/Voiceour/$file\", \"$digest\"),"
    done
    echo "    ]"
    echo "}"
} > "$MANIFEST"
echo "synced $(echo $FILES | wc -w | tr -d ' ') production sources into $DEST"
